def extract_tridiagonal(A):
    """
    Автоматически извлекает три диагонали из матрицы системы A (список списков).
    Проверяет, что матрица действительно трёхдиагональная (вне трёх диагоналей — нули).

    Возвращает:
        a - поддиагональ (a[0] = 0, не используется)
        b - главная диагональ
        c - наддиагональ (c[n-1] = 0, не используется)
    """
    n = len(A)
    a = [0.0] * n
    b = [0.0] * n
    c = [0.0] * n

    for i in range(n):
        for j in range(n):
            val = A[i][j]
            if j == i:
                b[i] = val
            elif j == i - 1:
                a[i] = val
            elif j == i + 1:
                c[i] = val
            else:
                if val != 0:
                    raise ValueError(
                        f"Матрица не трёхдиагональная: A[{i}][{j}] = {val} != 0"
                    )
    return a, b, c


def thomas_algorithm(a, b, c, d):
    """
    Метод прогонки (алгоритм Томаса) для решения СЛАУ с трёхдиагональной матрицей.

        a - поддиагональные элементы (a[0] не используется)
        b - диагональные элементы
        c - наддиагональные элементы (c[n-1] не используется)
        d - вектор правых частей
    """
    n = len(d)
    a, b, c, d = a[:], b[:], c[:], d[:]

    # Прямой ход
    for i in range(1, n):
        m = a[i] / b[i - 1]
        b[i] -= m * c[i - 1]
        d[i] -= m * d[i - 1]

    # Обратный ход
    x = [0.0] * n
    x[-1] = d[-1] / b[-1]
    for i in range(n - 2, -1, -1):
        x[i] = (d[i] - c[i] * x[i + 1]) / b[i]

    return x


def solve_tridiagonal_system(A, d):
    """Полный цикл: матрица + правая часть -> извлечение диагоналей -> решение."""
    a, b, c = extract_tridiagonal(A)
    return thomas_algorithm(a, b, c, d)


